package io.github.MVennn.GSAuxiliary.feature.navbar

import io.github.MVennn.GSAuxiliary.core.TargetApp

/**
 * 「手势导航条（小白条）同色」的调参常量。
 *
 * ## 一、为什么会有那条纯黑 / 纯白
 *
 * 宿主 targetSdk 30（见 `docs/reference/apk-analysis-report.md`），
 * **全程非沉浸** —— 没有 `setDecorFitsSystemWindows(false)`，Android 15 的
 * 「targetSdk 35+ 强制沉浸」也轮不到它。于是屏幕最下面那一条不属于宿主内容，
 * 由 `DecorView` 按 `window.navigationBarColor` 自己填；
 * 这个值宿主没设（或设了透明），就落回主题的 `windowBackground` ——
 * **深色模式纯黑、浅色模式纯白**，与上面的界面毫无过渡。
 *
 * 换句话说：**那块区域是宿主的窗口自己画的**，不是系统画的。
 * 所以也不用去做「真沉浸」（把内容铺到物理底边再补 inset）——
 * 只要把 `navigationBarColor` 换成「紧邻界面那一行的颜色」就融合了。
 *
 * ## 二、取色带在哪
 *
 * ```
 * ┌──────────────────────────┐
 * │  状态栏                   │  ← 不在本功能的范围内
 * ├──────────────────────────┤
 * │                          │
 * │  宿主内容（decor 已布局）  │
 * │                          │
 * ├──────────────────────────┤ ← decor.height - navBarHeight  ← 取色带下沿
 * │  ██ 取色带 BAND_DP 高 ██  │ ← 取的就是这一行的真实颜色
 * ├──────────────────────────┤
 * │  小白条（DecorView 填色）  │ ← 我们把这里换成上面取到的颜色
 * └──────────────────────────┘
 * ```
 *
 * 关键点：**取色带必须落在「内容最后一行」，不能落在导航条里**。
 * `decorView` 是整窗高度（导航条那一块也是它的孩子），
 * 所以必须先把 `navBarHeight` 减掉 —— 否则取到的是**自己上一次填进去的颜色**，
 * 会自我循环、永远不变。
 *
 * ## 三、两档取色 + 一条兜底
 *
 * | 档 | 手段 | 特点 |
 * |---|---|---|
 * | ① 结构合成 | 沿「取色带覆盖链」逐级合成背景色 | **同步**、零分配、首帧就能给结果 |
 * | ② 像素校准 | `PixelCopy` 拷那一行真实像素取平均 | **异步**、是屏幕上的真值，能救渐变 / 图片 / 圆角 |
 * | ③ 兜底 | 主题 `windowBackground` 当合成底色 | ①②都拿不到时至少不是黑/白硬块 |
 *
 * ① 先落地（保证首帧就有色），② 再异步校准（色差超过 [PIXEL_DELTA] 才改）。
 * ② 有**次数上限**：`PixelCopy` 在部分机型 / 部分窗口上恒失败，不能无限重试。
 */
object NavBarTargets {

    const val TARGET_PKG = TargetApp.PACKAGE

    /**
     * 取色带高度（dp）。
     *
     * 太薄（1px）容易正好压在一条分隔线 / 发丝线上，取到线的颜色；
     * 太厚会混进文字与图标。3dp（本机 416dpi ≈ 8px）是折中。
     */
    const val BAND_DP = 3

    /**
     * 结构取色结果的**最低不透明度**（0–255）。
     *
     * 合成完还低于这个值 = 整条链上没有任何一层给了实心背景（极端情况），
     * 这时候宁可不给结果，也不拿一个半透明的色去填导航条（会透出窗口底色）。
     */
    const val MIN_ALPHA = 250

    /**
     * 结构取色时，子视图要算「覆盖取色带」的**最小宽度占比**（相对父容器）。
     *
     * 底栏一行里六格并列，每格只占 1/6；真正代表「周边界面」的是**整行**。
     * 逐级取「最宽的那一层」就能稳定落在整行 / 页面容器上，
     * 不会被某一格自己的选中态底色带偏。
     */
    const val MIN_COVER_RATIO = 0.55f

    /**
     * 合成链的最大深度。
     *
     * 纯防御：宿主视图层级再深也不会超过 24 层，超了就当认不出来。
     */
    const val MAX_CHAIN_DEPTH = 24

    /** 布局回调节流（ms）—— 颜色不会每帧都变，没道理每帧都算一遍 */
    const val LAYOUT_THROTTLE_MS = 250L

    /**
     * 像素校准的最小间隔（ms）。
     *
     * `PixelCopy` 是跨进程拷Surface，比一次树遍历贵得多，必须限频。
     */
    const val PIXEL_COOLDOWN_MS = 2000L

    /**
     * 像素校准的**连续失败**次数上限（熔断）。
     *
     * `PixelCopy` 在**部分机型 / 无 backing surface 的窗口**上恒失败 ——
     * 连续失败到这个数就停手，留着结构取色的结果，不要在后台一直白拷。
     *
     * 只数**连续**失败：任何一次成功都把计数清零。健康窗口可以一直校准下去
     * （页面内容变了才救得回来），真正拷不出来的窗口照样很快熔断 ——
     * 旧版按「总共 N 次」封顶，长驻页面在校准耗尽后就永久失明了。
     */
    const val PIXEL_MAX_FAILS = 3

    /**
     * 像素校准值与当前已应用颜色的**色差阈值**（0–255，取 RGB 最大通道差）。
     *
     * 低于它说明两者肉眼上是一个颜色 —— 不折腾，省掉一次无意义的窗口属性刷新。
     */
    const val PIXEL_DELTA = 24

    /**
     * 像素采样的位图宽度。
     *
     * `PixelCopy` 会把源矩形**缩放**到目标位图，所以 `SAMPLE_W × 1` 等于
     * 「把整条取色带横向压成 32 个采样点」—— 足够抹掉噪点，又能保留横向色差。
     */
    const val SAMPLE_W = 32

    /**
     * 像素校准「源暂不可用」（NO_DATA / SOURCE_INVALID）的**主动重试**上限。
     *
     * 这两类返回是「窗口此刻拷不出」（首帧未渲染完、recreate、转屏），等下一次
     * 布局回调再试可能要 3-5 秒（详情页布局回调稀疏）—— 主动 300ms 重试一次
     * 能把首帧上色压进 1 秒。计数防的是「窗口一直不 ready」时烧 CPU：
     * 到顶就停手等布局回调；任何一次成功都会清零。
     */
    const val PIXEL_TRANSIENT_MAX = 10

    /**
     * 判定「背景是浅色」的亮度阈值（0–1）。
     *
     * 用来决定导航条上那条小横杠画深色还是浅色：背景亮 → 横杠要深色，
     * 否则融为一体看不见。`0.5` 是 WCAG 相对亮度中规中矩的分界。
     */
    const val LIGHT_LUMINANCE = 0.5f

    /**
     * 把 `Drawable` 渲出来读色时的绘制边长（px）。
     *
     * 渲到一块这么大的正方形画板，然后沿**中轴取三点平均**：
     * 中轴避开左右圆角（圆角背景的圆弧外是透明的，只读左上角一像素的旧法
     * 会读出空），三点平均让渐变背景拿到的是中下部的代表色，
     * 而不是只有顶上那一角。
     */
    const val SAMPLE_EDGE_PX = 16
}
